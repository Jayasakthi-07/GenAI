import { Sparkles } from 'lucide-react';
import { cn } from '@/lib/utils';
import { Tooltip } from '../ui/menus';

/**
 * The single, consistent marker for AI-generated content. Rule-based output (no model available)
 * uses the same slot with a neutral "Rule-based" label so the two are never confused.
 */
export function AiMarker({
  model,
  source = 'ai',
  className,
}: {
  model?: string | null;
  source?: 'ai' | 'rule';
  className?: string;
}) {
  if (source === 'rule') {
    return (
      <Tooltip content="Generated by deterministic rules because no AI model was available.">
        <span
          className={cn(
            'inline-flex items-center gap-1 rounded-sm bg-neutral-soft px-1.5 py-0.5 text-[11px] font-medium text-fg-secondary',
            className,
          )}
        >
          Rule-based — AI unavailable
        </span>
      </Tooltip>
    );
  }
  const label = (
    <span
      className={cn(
        'inline-flex items-center gap-1 rounded-sm bg-accent-soft px-1.5 py-0.5 text-[11px] font-semibold tracking-wide text-accent-text',
        className,
      )}
    >
      <Sparkles className="size-3" strokeWidth={2} aria-hidden />
      AI
      {model && <span className="font-medium tracking-normal">· {model}</span>}
    </span>
  );
  return model ? label : <Tooltip content="Written by an AI agent">{label}</Tooltip>;
}
